/**
 * Compile Phonix Desk's stylesheet.
 *
 *     npm install
 *     node tools/build-desk-css.mjs
 *
 * This runs by hand, not in the build - the same arrangement as
 * `build-editor.mjs` and `generate-icons.mjs`, and for the same reason. The
 * output is committed, so building and deploying Phonix needs cargo and
 * nothing else. Node is required only to *change* how Desk looks, which is a
 * deliberate edit by somebody who has already opened the stylesheet.
 *
 * That matters more here than it does for the editor. `phonix-desk` is a plain
 * `cargo build` with no cargo-leptos in front of it, so there is nothing in its
 * build that could run Tailwind even if we wanted it there - and a second
 * binary whose deployment needs npm on the box is a second way for a release to
 * fail at the moment the tool is wanted.
 *
 * # The name carries a hash, and the file is compiled in
 *
 * Unlike the editor bundle, this is not served out of `public/`: Desk has no
 * static directory and should not grow one for a single file. The bytes are
 * `include_str!`d into the binary and served from a route, which keeps Desk a
 * single artefact - copy the binary, run it.
 *
 * The hash is still in the URL, for the ordinary reason: a stylesheet served
 * under a name that never changes while its contents do is a browser holding
 * last month's layout. Hashed, it can be cached forever and can never be stale.
 * The Rust constant naming it is generated here at the same moment, so the two
 * cannot disagree.
 */

import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";
import { execFileSync } from "node:child_process";
import { readdirSync, mkdirSync, rmSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = join(root, "crates", "phonix-desk", "style", "desk.css");
const outDir = join(root, "crates", "phonix-desk", "assets");
const constantFile = join(root, "crates", "phonix-desk", "src", "assets.rs");
const scratch = join(outDir, ".desk.build.css");

mkdirSync(outDir, { recursive: true });

// The CLI rather than the JS API, because it is the same program cargo-leptos
// downloads and runs for the product - so the two applications are compiled by
// the same tool reading the same `theme.css`, and a Tailwind release that
// changes how a utility is emitted changes both or neither.
//
// The two do not share a *version*. cargo-leptos fetches its own binary into
// `~/.cache/cargo-leptos` and upgrades on its own schedule; this one is pinned
// in `package.json`. That is tolerable because the drift is visible - both
// stylesheets are rebuilt from source and neither is written by hand - and the
// alternative is teaching one build to find the other's cache.
execFileSync(
    join(root, "node_modules", ".bin", "tailwindcss"),
    ["--input", entry, "--output", scratch, "--minify"],
    { cwd: root, stdio: ["ignore", "ignore", "inherit"] },
);

const contents = readFileSync(scratch);
rmSync(scratch);

const hash = createHash("sha256").update(contents).digest("hex").slice(0, 12);
const name = `desk.${hash}.css`;
// Level 9 because the file is written once and read many times.
const gzipped = gzipSync(contents, { level: 9 }).length;

// Every previous build, removed. Left alone they accumulate one file per edit,
// all of them compiled into the binary by nothing and committed by habit.
for (const existing of readdirSync(outDir)) {
    if (/^desk\.[0-9a-f]+\.css$/.test(existing) && existing !== name) {
        rmSync(join(outDir, existing));
        console.log(`  removed ${existing}`);
    }
}

writeFileSync(join(outDir, name), contents);

// `\n` explicitly, and no trailing spaces: `.gitattributes` normalises this
// tree to LF, and a generated file that comes back CRLF on a Windows checkout
// is a whole-file diff on every run - and, for a file the migration checksums
// have already taught this project about, a real bug rather than noise.
const source = `//! Where Desk's stylesheet is, and what is in it.
//!
//! Generated by \`node tools/build-desk-css.mjs\`. Do not edit: the hash in the
//! URL is the hash of the file the script wrote, and changing one without the
//! other serves a page that points at nothing.
//!
//! The file's size is not published here. The editor bundle publishes its
//! weight because a screen in the product quotes it; Desk has nowhere to show
//! a number, and a constant nothing reads is a fact that stops being true
//! quietly. The script prints it when it runs.

/// The stylesheet's URL.
///
/// Named by [\`base.html\`](../templates/base.html) and answered by
/// [\`crate::routes::stylesheet\`]. The hash means a browser may keep it
/// forever, and that a changed stylesheet is a different address rather than a
/// stale copy.
pub const STYLESHEET: &str = "/assets/${name}";

/// The bytes themselves, compiled into the binary.
///
/// Desk is one artefact: copy the binary, run it. A static directory beside it
/// is a second thing to deploy and a second thing to get wrong.
pub const STYLESHEET_CSS: &str = include_str!("../assets/${name}");
`;

writeFileSync(constantFile, source.replace(/\r\n/g, "\n"));

console.log(`  wrote crates/phonix-desk/assets/${name}`);
console.log(
    `  ${(contents.length / 1024).toFixed(1)} KiB uncompressed, ` +
    `${(gzipped / 1024).toFixed(1)} KiB gzipped`,
);
console.log("  wrote crates/phonix-desk/src/assets.rs");
